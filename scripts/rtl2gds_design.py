"""Design manifest, frozen inputs, tool pins and status algebra of the RTL-to-GDS gate.

A design manifest (schema ``rustroad.design.v2``, ``fixtures/designs/<name>.json``,
documented in docs/rtl2gds.md) names the RTL, the top module and its clock
(``clock.port`` is ``null`` for a combinational design: ``clock.name`` is then a
virtual clock that only times the I/O), the SDC (primary/virtual-clock SDC
plus an I/O template rendered from the RTL port list), the physical recipe
(``recipe.physical``: ``legacy`` fixed-order placer + lattice router with a
tracked floorplan, or ``track`` analytic placer + track router whose floorplan
is regenerated by ``rustroad floorplan`` from ``recipe.floorplan`` and must be
byte-identical to the tracked one), per-PDK floorplan / physical / routing /
delay-cell / RC-profile references, the verification parameters and the
budgets. Every tracked file is pinned by SHA-256; the rendered SDC and every
PDK file the closure engine derives (Liberty per corner, LEFs, cell GDS,
OpenRCX rules) are frozen by hash as well. Tool binaries are pinned in a
separate tool file (``fixtures/flow/rtl2gds-tools.json``).

The gating thresholds cannot be loosened by a manifest: ``OWNER_FLOORS``
(hold >= +0.05 ns, setup >= 0 ns, RustSTA-vs-OpenSTA parity <= 1 ps, owner
decisions) and ``GATE_FLOORS`` (co-simulation vectors) are fixed here, and a
budget that loosens one fails ``budget_floors``. The manifest itself must be
the git-tracked file unchanged at HEAD (``manifest_provenance``), and the tool
pin file must be the one the manifest freezes; otherwise the gate cannot pass.

Statuses are ``passed`` / ``failed`` / ``unverified`` (``missing`` counts as
unverified), ``not_applicable`` and ``deviation_declared``. The last status is
accepted only for timing accuracy after the owner-approved MPW proof and
remains explicit in the aggregate; it does not widen the ordinary tolerance.
``not_applicable`` is accepted for a gating
item only where ``NOT_APPLICABLE`` (fixed here, not in the manifest) allows it,
and the caller must have proved the condition; it is listed separately in the
summary (``not_applicable_items``), never folded silently into ``passed``. A
definitive failure of any gating item fails the gate (exit 1); otherwise any
unproven gating item leaves it unverified (exit 3); exit 0 only when every
gating item passed or is an allowed ``not_applicable``. Pure functions here are
unit-tested (scripts/tests/test_rtl2gds.py).
"""
from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path
import re
from string import Template
import subprocess

ROOT = Path(__file__).resolve().parents[1]
DESIGN_SCHEMA = "rustroad.design.v3"
RECIPES = ("legacy", "track")
TOOLS_SCHEMA = "rustroad.rtl2gds-tools.v1"
SUMMARY_SCHEMA = "rustroad.rtl2gds.v1"
EXIT = {"passed": 0, "deviation_declared": 0, "failed": 1, "unverified": 3}
MAX_MANIFEST_BYTES = 1024 * 1024


class GateError(RuntimeError):
    """A gate step could not produce a verdict (maps to unverified)."""


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def resolve(path: str | Path) -> Path:
    p = Path(path)
    return p if p.is_absolute() else (ROOT / p)


# ----------------------------------------------------------------------------- statuses

# Gating items that may be ``not_applicable`` and the only condition under
# which the gate code emits it (the evidence is recorded with the item).
NOT_APPLICABLE = {
    "mpw_min_period": "combinational design (no clock port, virtual I/O clock only): no sequential or "
                      "clocked cell, RustSTA pulse_width_status unconstrained with zero pulse-width and "
                      "period rows, OpenSTA zero min-pulse-width and period rows at every corner",
}


def item(status: str, reason: str | None = None, **extra) -> dict:
    if status not in ("passed", "deviation_declared", "failed", "unverified", "missing", "not_applicable"):
        raise ValueError(f"unknown status {status!r}")
    out = dict(status=status)
    if reason:
        out["reason"] = reason
    out.update(extra)
    return out


def worst(statuses) -> str:
    """failed > unverified > deviation_declared > passed; empty is unverified.

    ``not_applicable`` parts do not change the verdict of the others; a list
    of only ``not_applicable`` parts is ``not_applicable``."""
    statuses = list(statuses)
    if not statuses:
        return "unverified"
    if "failed" in statuses:
        return "failed"
    applicable = [s for s in statuses if s != "not_applicable"]
    if not applicable:
        return "not_applicable"
    if any(s not in ("passed", "deviation_declared") for s in applicable):
        return "unverified"
    if "deviation_declared" in applicable:
        return "deviation_declared"
    return "passed"


def overall(per_pdk: dict[str, dict[str, dict]], gating: list[str], global_items: dict[str, dict],
            required_pdks: list[str]) -> dict:
    """Combine per-PDK gating statuses and global items into the gate verdict.

    Every required PDK must be present with every gating item; a missing item
    is unverified, never passed.
    """
    failed, unverified, not_applicable, declared = [], [], [], []
    for tag in required_pdks:
        statuses = per_pdk.get(tag)
        if statuses is None:
            unverified.append(f"{tag}:pdk_run")
            continue
        for key in gating:
            st = (statuses.get(key) or {}).get("status", "missing")
            if st == "failed":
                failed.append(f"{tag}:{key}")
            elif st == "not_applicable" and key in NOT_APPLICABLE:
                not_applicable.append(f"{tag}:{key}")
            elif st == "deviation_declared" and key == "timing_accuracy":
                declared.append(f"{tag}:{key}")
            elif st != "passed":
                unverified.append(f"{tag}:{key}")
    for key, value in global_items.items():
        st = (value or {}).get("status", "missing")
        if st == "failed":
            failed.append(f"*:{key}")
        elif st != "passed":
            unverified.append(f"*:{key}")
    status = "failed" if failed else "unverified" if unverified else "deviation_declared" if declared else "passed"
    return dict(status=status, exit_code=EXIT[status], failed_items=failed, unverified_items=unverified,
                not_applicable_items=not_applicable, declared_deviations=declared)


# ----------------------------------------------------------------------------- manifest

REQUIRED_KEYS = ("schema", "name", "top", "rtl", "clock", "sdc", "recipe", "stretch", "pdks_unavailable",
                 "pdk_profiles", "cell_policy", "signoff_manifest", "tools", "pdks", "verification", "budgets")
PDK_KEYS = ("floorplan", "physical_config", "routing_config", "delay_cells", "gds_layer_map",
            "rc_profiles", "corners", "frozen", "sdc_clock")
SDC_KEYS = ("reference_clock", "io_template", "period_derivation")
# Optional per-PDK tracked files: the track recipe's physical profile (input of
# ``rustroad floorplan``), a literal mapped netlist that replaces synthesis,
# the sizing profile that enables the gate-sizing ECO in the closure loop, and
# a per-PDK floorplan recipe that replaces recipe.floorplan for that PDK.
PDK_OPTIONAL = ("physical_profile", "netlist", "sizing_profile", "floorplan_recipe")
FLOORPLAN_RECIPE_KEYS = ("utilization", "aspect", "margin_um")
PDK_FILES = ("physical_profile", "netlist", "sizing_profile")  # optional tracked files
BUDGET_KEYS = ("hold_margin_ns", "hold_eco_target_margin_ns", "setup_margin_ns", "hold_eco_setup_margin_ns", "parity_ns",
               "max_hold_iterations", "process_timeout_s", "process_memory_mib", "max_wall_s",
               "container_memory", "container_timeout_s")
VERIFICATION_KEYS = ("cosim_vectors", "cosim_seed", "rustsys_budget", "rustsys_model_budget",
                     "rustsys_sweep_max_candidates", "yosys_equiv_seq")


# Owner-fixed gate thresholds: a manifest may tighten them, never loosen them.
OWNER_FLOORS = {
    "hold_margin_ns": (">=", 0.05, "hold >= +0.05 ns at tt/ss/ff (owner decision)"),
    "setup_margin_ns": (">=", 0.0, "setup >= 0 at ss+max and tt (owner decision)"),
    "parity_ns": ("<=", 0.001, "RustSTA-vs-OpenSTA endpoint parity <= 1 ps (owner decision)"),
}
# Gate policy floors on the verification block (not owner-fixed, same rule).
GATE_FLOORS = {
    "cosim_vectors": (">=", 1024, "random co-simulation of at least 1024 cycles (gate policy)"),
}


def budget_floors(budgets: dict, verification: dict) -> dict:
    """Every owner/gate threshold of the manifest against its fixed floor.

    A non-numeric, non-finite or loosened value fails; tightening passes.
    """
    rows, loosened = {}, []
    for block, floors, values in (("budgets", OWNER_FLOORS, budgets), ("verification", GATE_FLOORS, verification)):
        for key, (op, floor, rule) in floors.items():
            value = values.get(key)
            numeric = isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)
            ok = numeric and (value >= floor if op == ">=" else value <= floor)
            rows[f"{block}.{key}"] = dict(value=value, required=f"{op} {floor}", rule=rule,
                                          status="passed" if ok else "failed")
            if not ok:
                loosened.append(f"{block}.{key}={value!r} (required {op} {floor})")
    # The closure loop's hold target may only add a guard band on top of the gate's hold margin.
    target, margin = budgets.get("hold_eco_target_margin_ns"), budgets.get("hold_margin_ns")
    numeric = all(isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v) for v in (target, margin))
    ok = numeric and target >= margin
    rows["budgets.hold_eco_target_margin_ns"] = dict(value=target, required=f">= budgets.hold_margin_ns ({margin})",
                                                     rule="the ECO hold target is the gate margin plus a guard band",
                                                     status="passed" if ok else "failed")
    if not ok:
        loosened.append(f"budgets.hold_eco_target_margin_ns={target!r} (required >= hold_margin_ns {margin!r})")
    return item("passed" if not loosened else "failed",
                None if not loosened else f"manifest loosens fixed thresholds: {loosened}", floors=rows)


def manifest_provenance(path: Path, root: Path = ROOT) -> dict:
    """The design manifest must be git-tracked and unchanged at HEAD.

    Its budgets and frozen hashes define what the gate checks, so a copy or an
    uncommitted edit can never yield a pass (unverified, never passed).
    """
    path = Path(path).resolve()
    try:
        rel = path.relative_to(Path(root).resolve())
    except ValueError:
        return item("unverified", f"design manifest {path} is outside the repository {root}", path=str(path))

    def git(*args):
        return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, timeout=60)
    try:
        head = git("rev-parse", "--verify", "--quiet", "HEAD")
        at_head = git("rev-parse", "--verify", "--quiet", f"HEAD:{rel.as_posix()}")
        work = git("hash-object", "--", str(path))
    except (OSError, subprocess.SubprocessError) as error:
        return item("unverified", f"git unavailable: {error!r}", path=str(rel))
    if head.returncode != 0 or work.returncode != 0:
        return item("unverified", "not a git checkout: the manifest cannot be bound to a revision", path=str(rel))
    head_blob, work_blob = at_head.stdout.strip(), work.stdout.strip()
    if at_head.returncode != 0:
        return item("unverified", f"{rel} is not tracked at HEAD", path=str(rel), head=head.stdout.strip(),
                    worktree_blob=work_blob)
    ok = head_blob == work_blob
    return item("passed" if ok else "unverified",
                None if ok else f"{rel} differs from HEAD (uncommitted edit)", path=str(rel),
                head=head.stdout.strip(), head_blob=head_blob, worktree_blob=work_blob)


def tool_pins_frozen(tools_file: Path, manifest: dict) -> dict:
    """The tool pin file in use must be the one the manifest freezes (by sha256)."""
    want = manifest["tools"]["sha256"]
    got = sha256_file(tools_file) if Path(tools_file).is_file() else None
    ok = got == want
    return item("passed" if ok else "failed",
                None if ok else f"tool pin file {tools_file} (sha256 {got}) is not the manifest's frozen pin file "
                                f"{manifest['tools']['path']} ({want})", path=str(tools_file), sha256=got)


def manifest_problems(m: dict) -> list[str]:
    """Schema check of a ``rustroad.design.v2`` manifest (empty list: valid)."""
    problems = [f"missing key {k}" for k in REQUIRED_KEYS if k not in m]
    if m.get("schema") != DESIGN_SCHEMA:
        problems.append(f"schema {m.get('schema')!r} is not {DESIGN_SCHEMA}")
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_$]*", str(m.get("top", ""))):
        problems.append("top is not a simple Verilog identifier")
    clock = m.get("clock")
    if not isinstance(clock, dict) or not isinstance(clock.get("name"), str) or \
            not (clock.get("port") is None or isinstance(clock.get("port"), str)):
        problems.append("clock must be {name, port} (port null: virtual I/O clock of a combinational design)")
    sdc = m.get("sdc") or {}
    problems += [f"sdc: missing {k}" for k in SDC_KEYS if k not in sdc]
    problems += [f"sdc: {k} is per PDK since v3 (pdks.<tag>.sdc_clock, frozen.sdc_postroute)"
                 for k in ("clock", "rendered_sha256") if k in sdc]
    recipe = m.get("recipe") or {}
    physical = recipe.get("physical")
    if physical not in RECIPES:
        problems.append(f"recipe.physical {physical!r} is not one of {RECIPES}")
    floor = recipe.get("floorplan")
    if physical == "track":
        if not isinstance(floor, dict) or any(not isinstance(floor.get(k), (int, float)) for k in FLOORPLAN_RECIPE_KEYS):
            problems.append(f"recipe.floorplan must give {FLOORPLAN_RECIPE_KEYS} for the track recipe")
    elif physical == "legacy" and floor is not None:
        problems.append("recipe.floorplan must be null for the legacy recipe (tracked floorplan only)")
    if not isinstance(m.get("stretch"), bool):
        problems.append("stretch must be a boolean")
    if not isinstance(m.get("pdks_unavailable"), dict):
        problems.append("pdks_unavailable must be an object {pdk: reason}")
    for tag, spec in (m.get("pdks") or {}).items():
        problems += [f"pdks.{tag}: missing key {k}" for k in PDK_KEYS if k not in spec]
        own = spec.get("floorplan_recipe")
        if own is not None and (physical != "track" or not isinstance(own, dict) or
                                any(not isinstance(own.get(k), (int, float)) for k in FLOORPLAN_RECIPE_KEYS)):
            problems.append(f"pdks.{tag}.floorplan_recipe must give {FLOORPLAN_RECIPE_KEYS} (track recipe only)")
        if physical == "track" and "physical_profile" not in spec:
            problems.append(f"pdks.{tag}: the track recipe needs physical_profile")
        if physical == "legacy" and "physical_profile" in spec:
            problems.append(f"pdks.{tag}: physical_profile belongs to the track recipe")
        unknown = set(spec) - set(PDK_KEYS) - set(PDK_OPTIONAL)
        if unknown:
            problems.append(f"pdks.{tag}: unknown keys {sorted(unknown)}")
    overlap = set(m.get("pdks") or {}) & set(m.get("pdks_unavailable") or {})
    if overlap:
        problems.append(f"PDKs both available and unavailable: {sorted(overlap)}")
    problems += [f"budgets: missing {k}" for k in BUDGET_KEYS if k not in m.get("budgets", {})]
    problems += [f"verification: missing {k}" for k in VERIFICATION_KEYS if k not in m.get("verification", {})]
    return problems


def load_manifest(path: Path) -> dict:
    path = Path(path)
    if path.stat().st_size > MAX_MANIFEST_BYTES:
        raise GateError(f"design manifest {path} exceeds {MAX_MANIFEST_BYTES} bytes")
    m = json.loads(path.read_text())
    problems = manifest_problems(m)
    if problems:
        raise GateError(f"design manifest {path}: " + "; ".join(problems))
    return m


def tracked_entries(m: dict) -> dict[str, dict]:
    """Every {path, sha256} entry of the manifest, keyed by a dotted name."""
    out = {}
    for i, r in enumerate(m["rtl"]):
        out[f"rtl.{i}"] = r
    for key in SDC_KEYS:
        out[f"sdc.{key}"] = m["sdc"][key]
    for key in ("pdk_profiles", "cell_policy", "signoff_manifest", "tools"):
        out[key] = m[key]
    for tag, spec in m["pdks"].items():
        for key in ("floorplan", "physical_config", "routing_config", "delay_cells", "gds_layer_map",
                    "sdc_clock") + PDK_FILES:
            if key in spec:
                out[f"pdks.{tag}.{key}"] = spec[key]
        for rc, entry in spec["rc_profiles"].items():
            out[f"pdks.{tag}.rc_profiles.{rc}"] = entry
    return out


def verify_tracked(m: dict) -> dict:
    """Hash every tracked manifest file; any difference is a failed identity."""
    rows, bad = {}, []
    for key, entry in tracked_entries(m).items():
        p = resolve(entry["path"])
        actual = sha256_file(p) if p.is_file() else None
        ok = actual == entry["sha256"]
        rows[key] = dict(path=str(p), expected=entry["sha256"], actual=actual, status="passed" if ok else "failed")
        if not ok:
            bad.append(key)
    return item("passed" if not bad else "failed", None if not bad else f"changed or missing: {bad}",
                files=rows, changed=bad)


CLOCK_PERIOD_FLOOR_NS, CLOCK_PERIOD_FACTOR = 10, 1.25


def clock_period_rule(delay_ns: float) -> int:
    """Owner rule: max(10 ns, round_up(1.25 x pre-layout ss critical-path delay, 1 ns))."""
    return max(CLOCK_PERIOD_FLOOR_NS, math.ceil(round(CLOCK_PERIOD_FACTOR * delay_ns, 6) - 1e-9))


def sdc_period(text: str) -> float | None:
    m = re.findall(r"(?m)^\s*create_clock\b[^\n]*-period\s+([0-9.]+)", text)
    return float(m[0]) if len(m) == 1 else None


def clock_period_status(m: dict, tools: dict[str, dict]) -> dict:
    """The per-PDK clock SDCs carry the period the tracked derivation computed.

    Re-checks (no timing run) the derivation record of
    ``scripts/derive_clock_period.py`` against the manifest: the rule's
    arithmetic, each clock SDC's period and hash, the reference SDC differing
    only in -period/-waveform, and that the record was made with the pinned
    RustSys/RustSTA and the manifest's cell policy. ``--check`` of that script
    re-runs the timing.
    """
    try:
        rec = json.loads(resolve(m["sdc"]["period_derivation"]["path"]).read_text())
        ref = resolve(m["sdc"]["reference_clock"]["path"]).read_text()
    except (OSError, ValueError, KeyError) as error:
        return item("unverified", f"clock-period record unreadable: {error!r}")
    problems, rows = [], {}
    if rec.get("schema") != "rustroad.clock-period.v1" or rec.get("design") != m["name"]:
        problems.append("record schema/design mismatch")
    if (rec.get("inputs") or {}).get("reference_clock_sdc", {}).get("sha256") != m["sdc"]["reference_clock"]["sha256"]:
        problems.append("record was derived from another reference clock SDC")
    if (rec.get("inputs") or {}).get("cell_policy", {}).get("sha256") != m["cell_policy"]["sha256"]:
        problems.append("record was derived with another cell policy")
    for name in ("rustsys", "rusteda", "ruststa"):
        want = (tools.get(name) or {}).get("expected_sha256") or (tools.get(name) or {}).get("sha256")
        if ((rec.get("inputs") or {}).get("tools") or {}).get(name) != want:
            problems.append(f"record was derived with another {name} than the pinned one")
    for tag, spec in m["pdks"].items():
        r = (rec.get("pdks") or {}).get(tag) or {}
        delay, period = r.get("critical_path_delay_ns"), r.get("period_ns")
        text = resolve(spec["sdc_clock"]["path"]).read_text()
        got = sdc_period(text)
        normalized = re.sub(r"-period\s+[0-9.]+", "-period P", re.sub(r"-waveform\s+\{[^}]*\}", "-waveform W", text))
        reference = re.sub(r"-period\s+[0-9.]+", "-period P", re.sub(r"-waveform\s+\{[^}]*\}", "-waveform W", ref))
        ok = (isinstance(delay, (int, float)) and period == clock_period_rule(delay) and got == period
              and (r.get("clock_sdc") or {}).get("sha256") == spec["sdc_clock"]["sha256"]
              and normalized == reference and (r.get("self_check") or {}).get("status") == "passed")
        rows[tag] = dict(critical_path_delay_ns=delay, period_ns=period, sdc_period_ns=got,
                         wire_model=(r.get("prelayout") or {}).get("wire_model"),
                         startpoint=(r.get("prelayout") or {}).get("startpoint"),
                         endpoint=(r.get("prelayout") or {}).get("endpoint"), status="passed" if ok else "failed")
        if not ok:
            problems.append(f"{tag}: period/SDC/record inconsistent")
    return item("passed" if not problems else "failed", None if not problems else "; ".join(problems),
                rule=rec.get("rule"), pdks=rows)


def compare_frozen(expected: dict[str, str], fingerprints: dict[str, dict]) -> dict:
    """Closure-engine frozen inputs (Flow.frozen()) against the manifest's hashes."""
    rows, bad = {}, []
    for key in sorted(set(expected) | set(fingerprints)):
        want = expected.get(key)
        got = (fingerprints.get(key) or {}).get("sha256")
        ok = want is not None and got == want
        rows[key] = dict(expected=want, actual=got, path=(fingerprints.get(key) or {}).get("path"),
                         status="passed" if ok else "failed")
        if not ok:
            bad.append(key)
    return item("passed" if not bad else "failed", None if not bad else f"frozen inputs differ: {bad}",
                files=rows, changed=bad)


# ----------------------------------------------------------------------------- ports and SDC

def ports_from_yosys_json(module: dict) -> list[dict]:
    """Ports in declaration order: name, direction, width, msb, lsb, bits (scalar names).

    Yosys JSON does not distinguish ``x`` from ``[0:0] x``; a one-bit port is
    treated as a scalar (a one-bit vector port is not supported).
    """
    out = []
    for name, port in module["ports"].items():
        width = len(port["bits"])
        offset = port.get("offset", 0)
        upto = bool(port.get("upto", 0))
        lo, hi = offset, offset + width - 1
        msb, lsb = (lo, hi) if upto else (hi, lo)
        vector = width > 1
        bits = [f"{name}[{i}]" for i in range(lo, hi + 1)] if vector else [name]
        out.append(dict(name=name, direction=port["direction"], width=width, msb=msb, lsb=lsb,
                        vector=vector, bits=bits))
    return out


def render_sdc(clock_sdc: str, template: str, ports: list[dict], clock_port: str | None, clock_name: str) -> str:
    """Clock SDC + the I/O template filled from the RTL port list.

    ${clock}: clock name; ${inputs}: every input port (declaration order);
    ${data_inputs}: inputs except the clock port; ${outputs}: every output port.
    ``clock_port`` None: a virtual clock (combinational design), every input
    is a data input.
    """
    names = [p["name"] for p in ports]
    if clock_port is not None and clock_port not in names:
        raise GateError(f"clock port {clock_port!r} is not a port of the RTL top")
    if any(p["direction"] == "inout" for p in ports):
        raise GateError("inout ports are not supported by the I/O SDC template")
    inputs = [p["name"] for p in ports if p["direction"] == "input"]
    outputs = [p["name"] for p in ports if p["direction"] == "output"]
    values = dict(clock=clock_name, inputs=" ".join(inputs), outputs=" ".join(outputs),
                  data_inputs=" ".join(n for n in inputs if n != clock_port))
    return clock_sdc + Template(template).substitute(values)


# ----------------------------------------------------------------------------- tools

def load_tools(path: Path, overrides: dict[str, str]) -> dict[str, dict]:
    """Pinned tool binaries with their identity status (missing/changed never pass)."""
    data = json.loads(Path(path).read_text())
    if data.get("schema") != TOOLS_SCHEMA:
        raise GateError(f"tool file {path}: schema {data.get('schema')!r} is not {TOOLS_SCHEMA}")
    out = {}
    for name, spec in data["tools"].items():
        if "path" not in spec:
            out[name] = dict(spec, status="passed", note="image identity verified by its own harness")
            continue
        p = Path(overrides[name]) if name in overrides else resolve(spec["path"])
        entry = dict(spec, path=str(p), expected_sha256=spec["sha256"], overridden=name in overrides)
        if not p.is_file():
            entry.update(status="missing", actual_sha256=None, reason=f"{name} not found at {p}")
        else:
            actual = sha256_file(p)
            entry.update(actual_sha256=actual, status="passed" if actual == spec["sha256"] else "failed",
                         reason=None if actual == spec["sha256"] else f"{name} sha256 {actual} != pinned {spec['sha256']}")
        out[name] = entry
    unknown = sorted(set(overrides) - set(out))
    if unknown:
        raise GateError(f"--tool overrides name unknown tools: {unknown}")
    return out


def tools_status(tools: dict[str, dict]) -> dict:
    statuses = {n: t["status"] for n, t in tools.items()}
    st = worst(["unverified" if s == "missing" else s for s in statuses.values()])
    bad = {n: s for n, s in statuses.items() if s != "passed"}
    return item(st, None if not bad else f"tool identity: {bad}", tools=statuses)


def floorplan_recipe(m: dict, tag: str) -> dict | None:
    """The `rustroad floorplan` recipe of one PDK (per-PDK override, else recipe.floorplan)."""
    return (m["pdks"][tag].get("floorplan_recipe") or m["recipe"]["floorplan"]) if m["recipe"]["floorplan"] else None
